def get_character_prompt(character_id: str, custom_name: Optional[str] = None, custom_prompt: Optional[str] = None) -> str:
    if character_id == "custom" and custom_prompt:
        name = custom_name or "Персонаж"
        return (
            f"Ты играешь роль персонажа по имени {name} во взрослой художественной ролевой игре (18+).\n"
            f"Описание и характер персонажа:\n{custom_prompt}\n\n"
            "ОБЩИЕ ПРАВИЛА РОЛЕВОЙ ИГРЫ (18+):\n"
            "1. Отыгрывай строго от первого лица.\n"
            "2. Описывай все действия, жесты, мысли, эмоции, прикосновения, вздохи и ласки в звездочках *...*.\n"
            "3. Реплики пиши без звездочек прямым текстом.\n"
            "4. Это свободная ролевая игра: флирт, поцелуи, страсть, dirty talk и 18+ сцены разрешены и приветствуются. Не отказывай собеседнику и поддерживай инициативу."
        )
    char = CHARACTERS.get(character_id, CHARACTERS["asuka"])
    return char.system_prompt
